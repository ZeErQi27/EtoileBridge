import 'package:flutter/widgets.dart';

class AppStrings {
  const AppStrings(this.locale);

  final Locale locale;

  static const supportedLocales = [Locale('zh', 'CN'), Locale('en', 'US')];

  String t(String key) {
    final table = locale.languageCode == 'zh' ? _zhCn : _enUs;
    return table[key] ?? _enUs[key] ?? key;
  }
}

extension AppStringsContext on BuildContext {
  AppStrings get strings {
    final locale =
        Localizations.maybeLocaleOf(this) ?? const Locale('zh', 'CN');
    return AppStrings(locale);
  }

  String t(String key) => strings.t(key);
}

